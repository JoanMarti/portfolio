// Build a link for a language-neutral path such as "/work/glencore-ctrm/".
export function href(lang: Lang, path = '/'): string {
  const clean = path.startsWith('/') ? path : `/${path}`;
  return url(lang === defaultLang ? clean : `/${lang}${clean}`);
}

